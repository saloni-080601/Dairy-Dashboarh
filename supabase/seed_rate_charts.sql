CREATE TABLE IF NOT EXISTS public.rate_charts (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    milk_type VARCHAR(20) NOT NULL CHECK (milk_type IN ('cow', 'buffalo')),
    clr INTEGER NOT NULL CHECK (clr >= 20 AND clr <= 40),
    fat NUMERIC(4, 1) NOT NULL CHECK (fat >= 0 AND fat <= 20),
    rate NUMERIC(6, 2) NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT TIMEZONE('utc'::text, NOW()),
    CONSTRAINT unique_rate_lookup UNIQUE (milk_type, clr, fat)
);

